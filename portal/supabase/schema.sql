create or replace function public.asf_admin_action(op text, target uuid, arg text default null)
returns text language plpgsql security definer set search_path=''
as $$
declare p public.asf_profiles%rowtype; result text;
begin
 if not public.asf_is_commander() then raise exception 'Not authorized'; end if;
 select * into p from public.asf_profiles where user_id=target for update;
 if not found then raise exception 'User not found'; end if;
 if op='approve' then
   if p.status='approved' then return p.military_code; end if;
   result:=coalesce(p.military_code,'ASF-'||lpad(nextval('public.asf_military_seq'::regclass)::text,6,'0'));
   update public.asf_profiles set status='approved',military_code=result,updated_at=now() where user_id=target;
 elsif op='suspend' or op='reject' then
   update public.asf_profiles set status=case when op='suspend' then 'suspended' else 'rejected' end,updated_at=now() where user_id=target;
   result:=op;
 elsif op='court_on' or op='court_off' then
   update public.asf_profiles set court_enabled=(op='court_on'),updated_at=now() where user_id=target;
   result:=op;
 elsif op='rank' then
   if arg not in ('جندي','جندي أول','عريف','وكيل رقيب','رقيب','رقيب أول','رئيس رقباء','ملازم','ملازم أول','نقيب','رائد','مقدم','عقيد','عميد','لواء','فريق','فريق أول') then raise exception 'Invalid rank'; end if;
   update public.asf_profiles set rank=arg,updated_at=now() where user_id=target; result:=arg;
 else raise exception 'Invalid operation';
 end if;
 insert into public.asf_audit(actor_id,action,target_id,detail) values(auth.uid(),op,target::text,jsonb_build_object('argument',arg));
 return result;
end; $$;
revoke all on function public.asf_admin_action(text,uuid,text) from public;
grant execute on function public.asf_admin_action(text,uuid,text) to authenticated;

create or replace function public.asf_set_delegation(target uuid, feature text, kind text, enabled boolean)
returns void language plpgsql security definer set search_path=''
as $$
begin
 if not public.asf_is_commander() then raise exception 'Not authorized'; end if;
 if feature not in ('reports.read','police.manage','court.manage','users.review') or (kind is not null and (feature<>'reports.read' or kind not in ('personnel','officers','joint','presidencies'))) then raise exception 'Invalid delegation'; end if;
 if enabled then
  if not exists(select 1 from public.asf_delegations where user_id=target and permission=feature and report_kind is not distinct from kind) then
   insert into public.asf_delegations(user_id,permission,report_kind) values(target,feature,kind);
  end if;
 else
  delete from public.asf_delegations where user_id=target and permission=feature and report_kind is not distinct from kind;
 end if;
 insert into public.asf_audit(actor_id,action,target_id,detail) values(auth.uid(),'delegation',target::text,jsonb_build_object('feature',feature,'kind',kind,'enabled',enabled));
end; $$;
revoke all on function public.asf_set_delegation(uuid,text,text,boolean) from public;
grant execute on function public.asf_set_delegation(uuid,text,text,boolean) to authenticated;

create or replace function public.asf_review_change(req uuid, allow_change boolean)
returns void language plpgsql security definer set search_path=''
as $$
declare r public.asf_change_requests%rowtype;
begin
 if not public.asf_is_commander() then raise exception 'Not authorized'; end if;
 select * into r from public.asf_change_requests where id=req and state='pending' for update;
 if not found then raise exception 'Request not found'; end if;
 if allow_change then
  update public.asf_profiles set game_name=r.new_game_name,discord_id=r.new_discord_id,updated_at=now() where user_id=r.user_id;
 end if;
 update public.asf_change_requests set state=case when allow_change then 'approved' else 'rejected' end,reviewed_at=now() where id=req;
 insert into public.asf_audit(actor_id,action,target_id) values(auth.uid(),'profile_change',req::text);
end; $$;
revoke all on function public.asf_review_change(uuid,boolean) from public;
grant execute on function public.asf_review_change(uuid,boolean) to authenticated;

create or replace function public.asf_review_report(report uuid, new_state text, new_note text)
returns void language plpgsql security definer set search_path=''
as $$
begin
 if not public.asf_is_commander() then raise exception 'Not authorized'; end if;
 if new_state not in ('new','reviewing','reviewed','needs_more') then raise exception 'Invalid state'; end if;
 if not exists(select 1 from public.asf_reports where id=report and deleted_at is null) then raise exception 'Report unavailable'; end if;
 insert into public.asf_reviews(report_id,state,note,updated_by,updated_at) values(report,new_state,left(coalesce(new_note,''),4000),auth.uid(),now())
 on conflict(report_id) do update set state=excluded.state,note=excluded.note,updated_by=excluded.updated_by,updated_at=excluded.updated_at;
 insert into public.asf_audit(actor_id,action,target_id) values(auth.uid(),'review',report::text);
end; $$;
revoke all on function public.asf_review_report(uuid,text,text) from public;
grant execute on function public.asf_review_report(uuid,text,text) to authenticated;

create or replace function public.asf_trash_report(report uuid, restore boolean default false)
returns void language plpgsql security definer set search_path=''
as $$
begin
 if not public.asf_is_commander() then raise exception 'Not authorized'; end if;
 update public.asf_reports set deleted_at=case when restore then null else now() end,
 deleted_by=case when restore then null else auth.uid() end
 where id=report and (not restore or deleted_at>now()-interval '30 days');
 if not found then raise exception 'Report unavailable'; end if;
 insert into public.asf_audit(actor_id,action,target_id) values(auth.uid(),case when restore then 'restore' else 'trash' end,report::text);
end; $$;
revoke all on function public.asf_trash_report(uuid,boolean) from public;
grant execute on function public.asf_trash_report(uuid,boolean) to authenticated;

