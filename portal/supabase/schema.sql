-- نفّذ على مشروع Supabase مخصص بعد مراجعة النسخة الاحتياطية.
-- لا تضف أي حساب للقائد تلقائياً. اربطه لاحقاً يدوياً بمُعرّف Auth UID.
create extension if not exists pgcrypto;
create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;

create table if not exists app_private.commanders (
  user_id uuid primary key references auth.users(id) on delete cascade
);
create sequence if not exists public.asf_military_seq start with 1;

create or replace function public.asf_is_commander()
returns boolean language sql stable security definer set search_path=''
as $$ select exists (select 1 from app_private.commanders where user_id=auth.uid()); $$;
revoke all on function public.asf_is_commander() from public;
grant execute on function public.asf_is_commander() to authenticated;

create table if not exists public.asf_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  game_name text not null check (length(trim(game_name)) between 2 and 80),
  discord_id text not null check (discord_id ~ '^[0-9]{17,20}$'),
  rank text not null check (rank in ('جندي','جندي أول','عريف','وكيل رقيب','رقيب','رقيب أول','رئيس رقباء','ملازم','ملازم أول','نقيب','رائد','مقدم','عقيد','عميد','لواء','فريق','فريق أول')),
  military_code text unique,
  status text not null default 'pending' check(status in ('pending','approved','suspended','rejected')),
  court_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create or replace function public.asf_create_profile() returns trigger language plpgsql security definer set search_path=''
as $$
begin
 -- This Auth instance also serves unrelated applications; only ASF-tagged signups create ASF profiles.
 if new.raw_user_meta_data->>'asf_portal' = 'true' then
   insert into public.asf_profiles(user_id,game_name,discord_id,rank)
   values(new.id, trim(coalesce(new.raw_user_meta_data->>'game_name','')),coalesce(new.raw_user_meta_data->>'discord_id',''),coalesce(new.raw_user_meta_data->>'rank',''));
 end if;
 return new;
end; $$;
drop trigger if exists asf_auth_created on auth.users;
create trigger asf_auth_created after insert on auth.users for each row execute function public.asf_create_profile();

create or replace function public.asf_approved() returns boolean language sql stable security definer set search_path=''
as $$ select exists(select 1 from public.asf_profiles where user_id=auth.uid() and status='approved'); $$;
revoke all on function public.asf_approved() from public;
grant execute on function public.asf_approved() to authenticated;

create or replace function public.asf_has_court() returns boolean language sql stable security definer set search_path=''
as $$ select public.asf_is_commander() or exists(select 1 from public.asf_profiles where user_id=auth.uid() and status='approved' and court_enabled); $$;
revoke all on function public.asf_has_court() from public;
grant execute on function public.asf_has_court() to authenticated;

create table if not exists public.asf_delegations(
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.asf_profiles(user_id) on delete cascade,
  permission text not null check (permission in ('reports.read','police.manage','court.manage','users.review')),
  report_kind text check (report_kind is null or report_kind in ('personnel','officers','joint','presidencies')),
  created_at timestamptz not null default now(),
  unique(user_id,permission,report_kind)
);
create or replace function public.asf_can_read_kind(k text) returns boolean
language sql stable security definer set search_path=''
as $$
 select k <> 'secret' and public.asf_approved() and exists(
  select 1 from public.asf_delegations d
  where d.user_id=auth.uid() and d.permission='reports.read'
  and (d.report_kind=k or d.report_kind is null)
 );
$$;
revoke all on function public.asf_can_read_kind(text) from public;
grant execute on function public.asf_can_read_kind(text) to authenticated;

create table if not exists public.asf_drafts(
 id uuid primary key default gen_random_uuid(),
 author_id uuid not null default auth.uid() references auth.users(id),
 kind text not null check(kind in ('personnel','officers','joint','presidencies','secret')),
 mode text not null check(mode in ('structured','free')),
 title text not null default '',
 body jsonb not null default '{}'::jsonb,
 updated_at timestamptz not null default now()
);
create table if not exists public.asf_reports(
 id uuid primary key default gen_random_uuid(),
 report_number bigint generated by default as identity unique,
 author_id uuid not null references auth.users(id),
 kind text not null check(kind in ('personnel','officers','joint','presidencies','secret')),
 mode text not null check(mode in ('structured','free')),
 title text not null check(length(trim(title)) between 3 and 180),
 body jsonb not null,
 sender_name text not null,
 sender_rank text not null,
 sender_code text not null,
 original_report_id uuid references public.asf_reports(id),
 pdf_path text not null unique,
 submitted_at timestamptz not null default now(),
 deleted_at timestamptz,
 deleted_by uuid references auth.users(id)
);
create table if not exists public.asf_reviews(
 report_id uuid primary key references public.asf_reports(id) on delete cascade,
 state text not null default 'new' check (state in ('new','reviewing','reviewed','needs_more')),
 note text not null default '',
 updated_by uuid references auth.users(id),
 updated_at timestamptz not null default now()
);
create table if not exists public.asf_change_requests(
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null default auth.uid() references auth.users(id),
 new_game_name text not null check(length(trim(new_game_name)) between 2 and 80),
 new_discord_id text not null check(new_discord_id ~ '^[0-9]{17,20}$'),
 state text not null default 'pending' check(state in ('pending','approved','rejected')),
 reviewed_at timestamptz,
 created_at timestamptz not null default now()
);
create table if not exists public.asf_court_cases(
 id uuid primary key default gen_random_uuid(),
 submitted_by uuid not null default auth.uid() references auth.users(id),
 subject text not null,
 details text not null,
 created_at timestamptz not null default now()
);
create table if not exists public.asf_court_decisions(
 case_id uuid primary key references public.asf_court_cases(id) on delete cascade,
 outcome text not null check(outcome in ('approved','rejected')),
 note text not null default '',
 decided_by uuid not null references auth.users(id),
 decided_at timestamptz not null default now()
);
create table if not exists public.asf_audit(
 id bigint generated always as identity primary key,
 actor_id uuid references auth.users(id),
 action text not null,
 target_id text not null,
 detail jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);

