create policy "profiles self or commander" on public.asf_profiles for select to authenticated using(user_id=auth.uid() or public.asf_is_commander());
create policy "delegations self or commander" on public.asf_delegations for select to authenticated using(user_id=auth.uid() or public.asf_is_commander());
create policy "drafts own" on public.asf_drafts for all to authenticated using(author_id=auth.uid() and public.asf_approved()) with check(author_id=auth.uid() and public.asf_approved());
create policy "reports restricted read" on public.asf_reports for select to authenticated using(
 (kind='secret' and public.asf_is_commander())
 or (kind<>'secret' and (public.asf_is_commander() or (public.asf_approved() and (author_id=auth.uid() or public.asf_can_read_kind(kind)))))
);
create policy "reports approved submit" on public.asf_reports for insert to authenticated with check(
 author_id=auth.uid() and public.asf_approved()
 and pdf_path like (auth.uid()::text || '/%')
 and sender_code=(select military_code from public.asf_profiles where user_id=auth.uid() and status='approved')
 and sender_name=(select game_name from public.asf_profiles where user_id=auth.uid() and status='approved')
 and sender_rank=(select rank from public.asf_profiles where user_id=auth.uid() and status='approved')
);
create policy "reviews read" on public.asf_reviews for select to authenticated using(
 exists(select 1 from public.asf_reports r where r.id=report_id)
);
create policy "change requests read" on public.asf_change_requests for select to authenticated using(user_id=auth.uid() or public.asf_is_commander());
create policy "change requests create" on public.asf_change_requests for insert to authenticated with check(user_id=auth.uid() and public.asf_approved() and state='pending' and reviewed_at is null);
create policy "court cases read" on public.asf_court_cases for select to authenticated using(public.asf_has_court() or submitted_by=auth.uid());
create policy "court cases create" on public.asf_court_cases for insert to authenticated with check(public.asf_approved() and submitted_by=auth.uid());
create policy "court decisions read" on public.asf_court_decisions for select to authenticated using(
 exists(select 1 from public.asf_court_cases c where c.id=case_id)
);
create policy "court decisions create" on public.asf_court_decisions for insert to authenticated with check(public.asf_has_court() and decided_by=auth.uid());
create policy "audit commander only" on public.asf_audit for select to authenticated using(public.asf_is_commander());

