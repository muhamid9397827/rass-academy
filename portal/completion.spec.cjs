const { chromium }=require('playwright');
const assert=require('node:assert/strict');
const {portalMock,academyState}=require('./completion-fixtures.cjs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/supabase.min.js',r=>r.fulfill({status:200,contentType:'application/javascript',body:portalMock}));
 await page.goto('http://127.0.0.1:8000/portal/');
 await page.locator('#workspace').waitFor({state:'visible'});
 await page.locator('[data-page="police"]').click();
 await page.locator('#investigationForm input[name="accused"]').fill('عسكري تجريبي');
 await page.locator('#investigationForm input[name="discord"]').fill('99999999999999999999');
 await page.locator('#investigationForm button').click();
 assert.match(await page.locator('#investigationPreview').textContent(),/الحكم المقترح/);
 await page.locator('#useInvestigation').click();
 assert.match(await page.locator('#caseForm textarea').inputValue(),/ملف تحقيق/);
 await page.locator('[data-page="court"]').click();
 assert.match(await page.locator('#warningRows').textContent(),/إنذار نشط تجريبي/);
 assert.doesNotMatch(await page.locator('#warningRows').textContent(),/إنذار منتهي تجريبي/);
 await page.locator('#warningScope').selectOption('archive');
 const archive=await page.locator('#warningRows').textContent();
 assert.match(archive,/إنذار منتهي تجريبي/);assert.match(archive,/إنذار ملغي تجريبي/);assert.doesNotMatch(archive,/إنذار نشط تجريبي/);
 await page.locator('[data-page="academy"]').click();
 await page.locator('#academyResultsRows').getByText('لا توجد نتائج مطابقة').waitFor();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'new views fit mobile');
 const academy=await browser.newPage();
 academy.on('pageerror',e=>errors.push(e.message));
 await academy.addInitScript(state=>localStorage.setItem('asf-portal-academy-v1:last-result',JSON.stringify(state)),academyState);
 let calls=0;
 await academy.route('**/functions/v1/asf-academy-results',route=>{
  calls++;
  return route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(calls===1?{saved:false}:{saved:true,receipt:'ACD-00000001',receivedAt:new Date().toISOString(),legacyStatus:'unconfirmed',result:{score:7,total:10,percentage:70,passed:true,passingPercentage:70,assignedRank:''}})});
 });
 await academy.goto('http://127.0.0.1:8000/portal/academy.html');
 await academy.locator('#start-facilities-training').click();
 await academy.locator('#resume-button').click();
 await academy.locator('#retry-result-button').click();
 await academy.locator('#submission-status.is-error').waitFor();
 assert.equal(await academy.locator('#retry-result-button').isVisible(),true,'retry remains after invalid acknowledgement');
 await academy.locator('#retry-result-button').click();
 await academy.locator('#submission-status.is-success').waitFor();
 assert.equal(await academy.locator('#result-receipt').textContent(),'ACD-00000001');
 assert.match(await academy.locator('#result-percentage').textContent(),/70/,'server grade replaces local grade');
 assert.equal(await academy.locator('#retry-result-button').isVisible(),false);
 assert.match(await academy.locator('#submission-status-text').textContent(),/لم يُؤكّد/,'legacy ambiguity remains explicit');
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: investigation referral, active/archive warnings, commander ledger, mobile layout and receipt retry UI');
})().catch(e=>{console.error(e);process.exit(1)});
